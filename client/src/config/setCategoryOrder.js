// «Прочее» и всё безымянное — в конец: это не раздел, а то, что не разложили.
export const MISC_CATEGORIES = new Set(['Прочее', 'other', '']);

// Место категории в сете: сохранённая расстановка главнее, потом этот список,
// потом алфавит.
export function categoryRank(setSlug, category, saved = []) {
  const i = saved.indexOf(category);
  if (i >= 0) return i;
  if (MISC_CATEGORIES.has(category)) return 9999;
  return (SET_CATEGORY_ORDER[setSlug] || {})[category] ?? 999;
}
