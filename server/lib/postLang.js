function normLang(lang) {
  return PHRASES[lang] ? lang : DEFAULT_LANG;
}

function phrases(lang) {
  return PHRASES[normLang(lang)];
}

const normKey = (s) => String(s || '').trim().toLowerCase().replace(/\s+/g, ' ').replace(/:$/, '');

function translateSpecKey(key, lang) {
  const l = normLang(lang);
  return SPEC_KEYS[normKey(key)]?.[l] || String(key || '').trim();
}

// «белый» → «ак», «белый, чёрный» → «ак, кара». Составное значение переводим
// по частям через запятую/слэш: цвета в карточках часто пишут именно так.
function translateSpecValue(value, lang) {
  const l = normLang(lang);
  const raw = String(value == null ? '' : value).trim();
  const whole = SPEC_VALUES[normKey(raw)]?.[l];
  if (whole) return whole;
  if (!/[,/]/.test(raw)) return raw;
  return raw
    .split(/\s*([,/])\s*/)
    .map(part => (part === ',' ? ', ' : part === '/' ? ' / ' : (SPEC_VALUES[normKey(part)]?.[l] || part)))
    .join('');
}

// Язык готового текста — по буквам, которых нет в соседнем алфавите: қ, ғ, ұ, і, ә
// бывают только в казахском, ө, ү, ң в наших текстах — признак кыргызского.
// Нужно там, где язык с формы не пришёл (свободный пост, старая публикация):
// подставить казахскому посту кыргызский призыв хуже, чем угадать по тексту.
// Ничего характерного нет — считаем текст русским, это остальные наши посты.
function detectLang(text) {
  const s = String(text || '');
  if (/[қғұіә]/i.test(s)) return 'kk';
  if (/[өүң]/i.test(s))   return 'ky';
  return 'ru';
}

