// Максимальная длина фразы в словарях — на сколько слов заглядывать вперёд.
// 6 — под самую длинную фразу «для использования внутри и снаружи помещений».
const MAX_PHRASE = 6;

const norm = (s) => String(s || '').toLowerCase().replace(/ё/g, 'е').replace(/[«»"'`.,]/g, '').trim();

// Русское ли слово: латиница и цифры — это бренд и модель, их не трогаем.
const isRu = (w) => /[а-яё]/i.test(w) && !/[a-z0-9]/i.test(w);

// Первая буква — заглавная, остальное как есть (модель «9SW» не ломаем).
const capitalize = (s) => (s ? s[0].toUpperCase() + s.slice(1) : s);

// Жадный поиск самого длинного совпадения: сначала пробуем 4 слова, потом 3, 2, 1.
function lookup(words, i, lang) {
  for (let len = Math.min(MAX_PHRASE, words.length - i); len >= 1; len--) {
    const key = norm(words.slice(i, i + len).join(' '));
    const hit = PHRASES[key] || MODIFIERS[key];
    if (hit && hit[lang]) return { text: hit[lang], len };
  }
  return null;
}

// «Гардеробная вешалка INFINITY белый» → «Кийим илгич INFINITY ак».
// Ничего не найдено — возвращаем исходное слово: полурусский заголовок честнее
// выдуманного перевода, и его видно в форме публикации, где можно поправить.
function translateName(title, lang) {
  if (!title || (lang !== 'ky' && lang !== 'kk')) return String(title || '');

  const words = String(title).split(/\s+/).filter(Boolean);
  const out = [];
  let i = 0;
  let translatedFirst = false;

  while (i < words.length) {
    // «1-дверный», «3-дверный» — цифра приклеена к слову, отдельным словом
    // такое в словаре не найдётся. Переводим только буквенную часть.
    const hyphen = words[i].match(/^(\d+)-([А-Яа-яЁё]+)$/);
    if (hyphen) {
      const one = MODIFIERS[norm(hyphen[2])] || PHRASES[norm(hyphen[2])];
      if (one && one[lang]) {
        out.push(`${hyphen[1]}-${one[lang]}`);
        i++;
        translatedFirst = true;
        continue;
      }
    }

    const hit = isRu(words[i]) ? lookup(words, i, lang) : null;
    if (hit) {
      out.push(out.length === 0 ? capitalize(hit.text) : hit.text);
      i += hit.len;
      translatedFirst = true;
    } else {
      out.push(words[i]);
      i++;
    }
  }

  // Ни одного слова не узнали — отдаём оригинал, чтобы не плодить «переводы»
  // вида «Zina Diamond» → «Zina Diamond» с изменённым регистром.
  return translatedFirst ? out.join(' ') : String(title);
}

// Название, вписанное руками в карточку товара, — оно всегда важнее словаря.
function manualName(product, lang) {
  const field = lang === 'kk' ? 'nameKk' : lang === 'ky' ? 'nameKy' : '';
  return field ? String(product?.[field] || '').trim() : '';
}

module.exports = { translateName, manualName, PHRASES, MODIFIERS };
