// Бренд и гео. Казахстанское направление живёт в Алматы — под казахским постом
// бишкекские теги бессмысленны.
const BRAND_TAGS = {
  'matkasym-home':   '#matkasymhome',
  'matkasym-shaar':  '#matkasymshaar',
  'matkasym-kyzmat': '#matkasym',
};
const GEO = {
  ky: ['#бишкек', '#кыргызстан'],
  kk: ['#алматы', '#казахстан'],
  ru: ['#бишкек', '#кыргызстан'],
};

const MAX_TAGS = 5;

// До двух тем: по категории и названию, иначе по сету.
function themeTags(product) {
  const haystack = [product?.category, product?.fullName || product?.name].filter(Boolean).join(' ');
  const found = [];
  for (const { re, tags } of THEMES) {
    if (!re.test(haystack)) continue;
    tags.forEach(t => { if (!found.includes(t)) found.push(t); });
    if (found.length >= 2) break;
  }
  if (found.length) return found.slice(0, 2);
  return (SET_THEMES[product?.set] || []).slice(0, 2);
}

// Хэштеги одной строкой. Пустая строка — если товара нет (свободный пост):
// придумывать тему посту, которого мы не знаем, нельзя.
function hashtagsFor(product, lang) {
  if (!product) return '';
  const brand = BRAND_TAGS[product.brand] || '#matkasym';
  const geo   = GEO[lang] || GEO.ky;

  const tags = [];
  for (const t of [...themeTags(product), brand, ...geo]) {
    if (t && !tags.includes(t)) tags.push(t);
    if (tags.length >= MAX_TAGS) break;
  }
  return tags.join(' ');
}

module.exports = { hashtagsFor, themeTags, THEMES, SET_THEMES, MAX_TAGS };
