// Тело поста: служебные строки (заголовок, сет, цена, призыв, характеристики,
// хэштеги) в объявление не идут — там свои колонки.
const bodyOf = (html) => String(html || '')
  .replace(/<[^>]+>/g, '')
  .split('\n')
  .filter(l => {
    const t = l.trim();
    if (!t) return false;
    if (/^[🆕📦💰✅📲•#]/.test(t)) return false;
    if (/^(Топтом|Баасы|Сет|Цена)\s*:/i.test(t)) return false;
    return true;
  })
  .join(' ').replace(/\s{2,}/g, ' ').trim();

// Цвета и количество в упаковке у привозных товаров лежат прямо в названии, а
// характеристик в карточке нет вовсе. Достаём их оттуда, а не выдумываем: пустая
// колонка в объявлении хуже, чем два честных факта.
const COLOR_KY = {
  black: 'кара', white: 'ак', grey: 'боз', pink: 'кызгылтым',
  green: 'жашыл', blue: 'көк', beige: 'бежевый',
};
// Границы слов обязательны: без них «для белья» читалось как «белый».
// Хвост слова проверяем сами: \b в JS считается по латинице и с кириллицей
// не срабатывает — иначе «для белья» читалось бы как «белый».
const tail = '(?![а-яё])';
const COLOR_RU = [
  [new RegExp('ч[её]рн(ый|ая|ое)' + tail, 'i'), 'кара'],
  [new RegExp('бел(ый|ая|ое)' + tail, 'i'),     'ак'],
  [new RegExp('сер(ый|ая|о-бел[а-яё]*)' + tail, 'i'), 'боз'],
  [new RegExp('розов(ый|ая)' + tail, 'i'),      'кызгылтым'],
  [new RegExp('зел[её]н(ый|ая)' + tail, 'i'),   'жашыл'],
  [new RegExp('син(ий|яя)' + tail, 'i'),        'көк'],
];

function derivedSpecs(p) {
  const name = p.fullName || p.name || '';
  const out = [];
  if (p.dimensions) out.push(`Өлчөмү: ${p.dimensions}`);

  const color = COLOR_KY[p.color] || (COLOR_RU.find(([re]) => re.test(name)) || [])[1];
  if (color) out.push(`Түсү: ${color}`);

  // «8-p», «5-р», «10р», «(3шт)» — сколько штук в упаковке
  const pack = name.match(/(\d+)\s*-?\s*[pрп](?![а-яa-z])/i) || name.match(/\((\d+)\s*шт\)/i);
  if (pack) out.push(`Топтомдо: ${pack[1]} даана`);
  return out;
}

