const ky = (dict, translated, raw) => dict[String(raw).trim()] || dict[String(translated).trim()] || translated;

const specsLine = (p) => {
  const own = (p.specs || [])
    .filter(s => s && s.key && String(s.value).trim())
    .map(s => {
      const k = ky(SPEC_KEY_KY, translateSpecKey(s.key, 'ky'), s.key);
      const v = ky(SPEC_VAL_KY, translateSpecValue(s.value, 'ky'), s.value);
      // Длинные русские абзацы в характеристики не лезут — им место в описании
      return `${k}: ${String(v).length > 60 ? String(v).slice(0, 57).trim() + '…' : v}`;
    });
  const lines = own.length ? own : derivedSpecs(p);

  // Цвет берём из карточки, а не из характеристик: у «Keremet (Белая)» в specs
  // осталось «чёрный» от товара-близнеца, а поле color мы выставляли по чертежу.
  const colorKy = COLOR_KY[p.color] || (COLOR_RU.find(([re]) => re.test(p.fullName || p.name || '')) || [])[1];
  if (colorKy) {
    const i = lines.findIndex(l => /^(Цвет|Түсү)\s*:/i.test(l));
    if (i >= 0) lines[i] = `Түсү: ${colorKy}`;
    else lines.push(`Түсү: ${colorKy}`);
  }
  return lines.join('. ');
};

async function kyrgyzText(p) {
  const name = p.fullName || p.name || '';
  const manual = MANUAL[p.sku] || MANUAL[name]
    || (MANUAL_RE.find(([re]) => re.test(name)) || [])[1];
  const own = await Publication.findOne({ product: p._id, text: { $ne: '' } }).sort({ createdAt: -1 }).select('text').lean();
  if (own) { const b = bodyOf(own.text); if (b.length > 40) return { src: 'пост', text: b }; }

  const du = String(p.sku || '').match(/^(MKS-ДУ\d{4})/);
  if (du) {
    const sibs = await Product.find({ sku: new RegExp('^' + du[1]), _id: { $ne: p._id } }).select('_id').lean();
    for (const s of sibs) {
      const pub = await Publication.findOne({ product: s._id, text: { $ne: '' } }).sort({ createdAt: -1 }).select('text').lean();
      if (pub) { const b = bodyOf(pub.text); if (b.length > 40) return { src: 'собрат', text: b }; }
    }
  }
  return manual ? { src: 'вручную', text: manual } : { src: 'НЕТ', text: '' };
}

(async () => {
  await mongoose.connect(MONGO_URI);

  const all = await Product.find({
    set: SET,
    productStatus: { $in: ['for_sale', 'improvement'] },
    'images.0': { $exists: true },
  }).select('name fullName sku specs images stock color dimensions').lean();

  // Карточки-клоны: без артикула и без остатка. В объявления им нечего нести.
  const products = all.filter(p => p.sku || p.stock > 0);

  const rows = [];
  const stats = { пост: 0, собрат: 0, вручную: 0, 'НЕТ': 0 };
  const gaps = { text: [], specs: [] };

  for (const p of products) {
    const { src, text } = await kyrgyzText(p);
    stats[src]++;
    if (src === 'НЕТ') { gaps.text.push(p.fullName || p.name); continue; }

    const specs = specsLine(p);
    if (!specs) gaps.specs.push(p.fullName || p.name);

    const row = {
      'Артикул': p.sku || '',
      'Название': p.fullName || p.name || '',
      'Мүнөздөмөсү (характеристики)': specs,
      'Сүрөттөмөсү (описание)': text,
      'Баасы (цена)': PRICE,
    };
    COLUMNS.slice(5).forEach((col, i) => { row[col] = (p.images || [])[i] || ''; });
    rows.push(row);
  }

  const ws = xlsx.utils.json_to_sheet(rows, { header: COLUMNS });
  ws['!cols'] = [{ wch: 18 }, { wch: 46 }, { wch: 52 }, { wch: 70 }, { wch: 26 },
    ...Array(8).fill({ wch: 40 })];
  const wb = xlsx.utils.book_new();
  xlsx.utils.book_append_sheet(wb, ws, 'Лалафо');

  const file = path.join(os.homedir(), 'Desktop', `Лалафо_${NUM}_${LABEL.replace(/\s+/g, '_')}.xlsx`);
  xlsx.writeFile(wb, file);

  console.log(`Сет ${SET}: подходящих товаров ${products.length}, строк в файле ${rows.length}`);
  console.log(`Откуда описание: из поста ${stats['пост']}, из поста собрата ${stats['собрат']}, написано вручную ${stats['вручную']}`);
  if (gaps.text.length) {
    console.log(`\nНе попали — нет кыргызского описания (${gaps.text.length}):`);
    gaps.text.forEach(n => console.log('   ·', n));
  }
  if (gaps.specs.length) {
    console.log(`\nБез характеристик, колонка пустая (${gaps.specs.length}):`);
    gaps.specs.forEach(n => console.log('   ·', n));
  }
  console.log(`\n→ ${file}`);
  await mongoose.disconnect();
})().catch(e => { console.error(e); process.exit(1); });
