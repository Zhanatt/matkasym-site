def atlas_uri():
    """URI боевой базы — только из server/.env.atlas, как в lib/atlas.js."""
    env = SERVER / '.env.atlas'
    if env.exists():
        m = re.search(r'^\s*ATLAS_URI\s*=\s*(.+)$', env.read_text(encoding='utf-8'), re.M)
        if m:
            return m.group(1).strip().strip('"\'')
    if os.environ.get('ATLAS_URI'):
        return os.environ['ATLAS_URI']
    sys.exit('❌ Не задан ATLAS_URI (server/.env.atlas) — база сайта недоступна.')


def mmarket_price(retail):
    """Розница + 10%, округлённая вверх до сотни сом.

    Считаем целочисленно: 1680 * 1.1 на float даёт 1848.0000000000002 и цена уезжает.
    Округляем только вверх — вниз нельзя, иначе наценка окажется меньше 10%.
    """
    exact = -(-int(round(retail * 100)) * 11 // 1000)     # ceil(retail * 1.1)
    return -(-exact // 100) * 100                         # ceil до сотни


def discount_amount(sku, group):
    """Витринная скидка: случайные 100–500 сом ровными сотнями.

    На эту же сумму поднимается цена в колонке `price`, потому что Ммаркет вычитает
    скидку из неё (в инструкции: «не цена со скидкой, а именно сумма самой скидки»).
    Итог для покупателя = розница + 10% до сотни, но карточка показывает зачёркнутую цену.

    Засеваем группой, а не артикулом: цветовые варианты склеены в одну карточку, и разные
    скидки заставляли бы ценник прыгать при переключении цвета. У одиночных карточек группы
    нет — там сеем артикулом. Сумма при каждой пересборке та же, иначе цена на витрине
    менялась бы после каждого запуска скрипта.
    """
    return random.Random(group or sku).randrange(100, 501, 100)


def order_imgs(urls):
    """Ммаркет принимает только jpg/jpeg/png/webp и проверяет расширение в ссылке.

    Фото лежат в Cloudinary, а он отдаёт картинку в том формате, который спросили
    расширением, — поэтому .avif достаточно переписать на .jpg, файл конвертируется
    на лету и ни одного снимка не теряется. Проверено: все 47 avif-ссылок каталога
    отвечают content-type: image/jpeg.
    """
    return [re.sub(r'\.avif$', '.jpg', u, flags=re.I) for u in urls]


def seo_tail(sku):
    art, digits, alt = IKEA[sku]
    return f' Артикул IKEA: {art} / {digits}. Также ищут как: {alt}.'


def dictionaries(wb, sheet_title):
    """Словари категории: заголовок колонки → множество допустимых значений.

    Значения лежат на листе metadata, а колонки листа ссылаются на них
    именованными диапазонами `cat<id>_<Поле>` через проверку данных.
    """
    md = wb['metadata']
    out = {}
    ws = wb[sheet_title]
    for dv in ws.data_validations.dataValidation:
        name = str(dv.formula1 or '').lstrip('=')
        if name not in wb.defined_names:
            continue
        m = re.match(r"'?metadata'?!\$([A-Z]+)\$(\d+):\$[A-Z]+\$(\d+)", wb.defined_names[name].value)
        if not m:
            continue
        col, lo, hi = m.group(1), int(m.group(2)), int(m.group(3))
        allowed = {str(md[f'{col}{r}'].value) for r in range(lo, hi + 1) if md[f'{col}{r}'].value not in (None, '')}
        for rng in dv.sqref.ranges:                      # колонка вида P2:P10000
            header = ws.cell(1, rng.min_col).value
            if header:
                out[str(header).strip()] = allowed
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--template', default=str(DEFAULT_TEMPLATE), help='шаблон Ммаркет (с листом metadata)')
    ap.add_argument('--out', default=str(DEFAULT_OUT), help='куда сохранить заполненную книгу')
    a = ap.parse_args()

    template, out = Path(a.template).expanduser(), Path(a.out).expanduser()
    if not template.exists():
        sys.exit(f'❌ Шаблон не найден: {template}')

    # Работаем на копии шаблона: metadata, словари и выпадающие списки должны
    # доехать до площадки ровно такими, какими она их прислала.
    shutil.copyfile(template, out)
    wb = load_workbook(out)
    if 'metadata' not in wb.sheetnames:
        sys.exit(f'❌ В шаблоне нет листа metadata — площадка такой файл не примет: {template}')

    for sheet in dict.fromkeys(i[0] for i in ITEMS):
        if sheet not in wb.sheetnames:
            sys.exit(f'❌ В шаблоне нет листа «{sheet}». Скачайте шаблон с этой категорией в CRM Ммаркет.')

    db = MongoClient(atlas_uri()).get_default_database()
    skus = [i[1] for i in ITEMS]
    products = {p['sku']: p for p in db.products.find({'sku': {'$in': skus}})}
    if [s for s in skus if s not in products]:
        sys.exit('❌ Нет в базе сайта: ' + ', '.join(s for s in skus if s not in products))

    # Инструкция Ммаркет: варианты одной модели объединяются в карточку через
    # `similar_products_sku` — перечисление артикулов остальных вариантов через запятую.
    # Колонку «Группировка SKU» тоже заполняем: её проверяет валидатор загрузки.
    siblings = {}
    for _, sku, _, _, group, _, _, _ in ITEMS:
        if group:
            siblings.setdefault(group, []).append(sku)

    rows, skipped, empty_attrs = [], [], []

    for sheet in dict.fromkeys(i[0] for i in ITEMS):
        ws = wb[sheet]
        headers = {str(c.value).strip(): c.column for c in ws[1] if c.value}
        sku_col = next(col for h, col in headers.items() if h.startswith(SKU_HEADER))
        stock_col = next(col for h, col in headers.items() if h.startswith('Город'))
        allowed = dictionaries(wb, sheet)
        # характеристики — всё между служебными колонками и складом
        attr_headers = [h for h, col in headers.items()
                        if col > max(headers[b] for b in BASE_HEADERS if b in headers) and col != stock_col]

        for sh, sku, name, pkg, group, main_flag, attrs, desc in ITEMS:
            if sh != sheet:
                continue
            p = products[sku]
            retail = p.get('price') or 0
            net = mmarket_price(retail)          # то, что должно остаться после скидки
            discount = discount_amount(sku, group)
            weight, length, width, height = PKG[pkg]
            values = {
                'name': name, 'description': desc, 'price': net + discount,
                'discount': discount, 'images': ', '.join(order_imgs(p.get('images') or [])),
                'merge': ', '.join(x for x in siblings.get(group, []) if x != sku) or None,
                'group': group, 'event': None, 'pickup': 'Да', 'main': main_flag,
                'pkg_weight': weight, 'pkg_length': length, 'pkg_width': width, 'pkg_height': height,
            }

            r = ws.max_row + 1
            ws.cell(r, sku_col).value = sku
            for header, key in BASE_HEADERS.items():
                if header in headers:
                    ws.cell(r, headers[header]).value = values[key]
            ws.cell(r, stock_col).value = p.get('stock') or 0
            ws.cell(r, headers['Описание товара']).alignment = Alignment(wrap_text=True, vertical='top')

            filled = 0
            for header in attr_headers:
                v = attrs.get(header)
                if v is None:
                    empty_attrs.append((sku, header))
                    continue
                if header in allowed and str(v) not in allowed[header]:
                    skipped.append((sku, header, v))     # значения нет в словаре — оставляем пусто
                    continue
                ws.cell(r, headers[header]).value = v
                filled += 1

            rows.append((sheet, sku, name, retail, net, p.get('stock') or 0,
                         len(p.get('images') or []), filled, len(attr_headers)))

    wb.save(out)

    groups_by_sku = {i[1]: i[4] for i in ITEMS}

    print(f'Шаблон:   {template}')
    print(f'Записано: {out}\n')
    cur = None
    for sheet, sku, name, retail, price, stock, imgs, filled, total in rows:
        if sheet != cur:
            cur = sheet
            print(f'── {sheet}')
        d = discount_amount(sku, groups_by_sku[sku])
        print(f'   {sku:<16}{name[:46]:<48}розн {retail:>6}  витрина {price + d:>6} − скидка {d:>3} = {price:>6}'
              f'{stock:>4} шт  {imgs} фото  {filled}/{total}')

    if skipped:
        print(f'\n⚠️  Значений нет в словарях площадки, ячейки оставлены пустыми ({len(skipped)}):')
        for sku, header, v in skipped:
            print(f'   {sku:<16}{header:<32}{v}')

    if empty_attrs:
        by_header = {}
        for sku, header in empty_attrs:
            by_header.setdefault(header, []).append(sku)
        print(f'\nНезаполненные характеристики ({len(by_header)} полей) — данных нет:')
        print('   ' + ', '.join(sorted(by_header)))

    print(f'\nВсего позиций: {len(rows)}')


if __name__ == '__main__':
    main()
