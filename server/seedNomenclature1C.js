async function run() {
  await mongoose.connect(MONGO_URI);

  const products = await Product.find({ set: 'uzak-koldon' });
  console.log(`Товаров в сете uzak-koldon: ${products.length}\n`);

  let updated = 0, skipped = 0, missing = 0;

  for (const p of products) {
    const target = NAMES[p.sku];
    if (!target) {
      console.log(`  ⚠ нет названия для ${p.sku} — ${p.fullName || p.name}`);
      missing++;
      continue;
    }
    if (p.nomenclature1C === target) { skipped++; continue; }
    if (p.nomenclature1C && !FORCE) {
      console.log(`  ⏭ ${p.sku} уже заполнен вручную: ${p.nomenclature1C}`);
      skipped++;
      continue;
    }

    console.log(`  ${EXECUTE ? '✔' : '[dry]'} ${p.sku} → ${target}`);
    if (EXECUTE) {
      p.nomenclature1C = target;
      await p.save();
    }
    updated++;
  }

  const unusedSkus = Object.keys(NAMES).filter(sku => !products.some(p => p.sku === sku));
  if (unusedSkus.length) console.log(`\n⚠ Артикулы из скрипта, которых нет в базе: ${unusedSkus.join(', ')}`);

  console.log(`\nИтого: ${EXECUTE ? 'обновлено' : 'будет обновлено'} ${updated}, пропущено ${skipped}, без названия ${missing}`);
  if (!EXECUTE) console.log('Добавьте --execute для реальной записи.');

  await mongoose.disconnect();
}

run().catch(e => { console.error(e); process.exit(1); });
