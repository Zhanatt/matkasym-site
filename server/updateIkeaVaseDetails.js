async function uploadImage(url, key, idx) {
  const res = await cloudinary.uploader.upload(url, {
    folder: 'matkasym/home/ikea-vases',
    public_id: `${key}-${idx}`,
    overwrite: true,
  });
  return res.secure_url;
}

async function main() {
  console.log('Подключение к MongoDB Atlas...');
  await mongoose.connect(MONGO_URI);
  console.log('Подключено!\n');

  for (const item of ITEMS) {
    const m = manifest[item.key];
    const product = await Product.findById(item.id);
    if (!product) { console.log(`❌ Не найден: ${item.key}`); continue; }
    console.log(`\n=== ${product.name}`);

    // Фото: обычные (без схемы размеров) + схема размеров последней
    const gallery = m.images.filter(u => u !== m.meas_img).slice(0, MAX_GALLERY);
    if (m.meas_img) gallery.push(m.meas_img);

    const uploaded = [];
    for (let i = 0; i < gallery.length; i++) {
      try {
        const url = await uploadImage(gallery[i], item.key, i + 1);
        uploaded.push(url);
        console.log(`  📷 ${i + 1}/${gallery.length} загружено`);
      } catch (e) {
        console.log(`  ⚠️ фото ${i + 1} не загрузилось: ${e.message}`);
      }
    }

    // Существующее главное фото остаётся первым
    const existing = (product.images || []).filter(u => !u.includes('/ikea-vases/'));
    product.images = [...existing, ...uploaded];
    product.description = item.description;
    product.dimensions = item.dimensions;
    product.specs = item.specs.map(([key, value]) => ({ key, value, options: [] }));

    await product.save();
    console.log(`  ✅ обновлено: описание, размеры, ${item.specs.length} характеристик, ${uploaded.length} фото (итого ${product.images.length})`);
  }

  await mongoose.disconnect();
  console.log('\nГотово!');
}

main().catch(e => { console.error(e); process.exit(1); });
